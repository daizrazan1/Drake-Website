            <h2>Beginnings</h2>
            <p>Aubrey Drake Graham was born on October 24, 1986 in Toronto, Ontario. Raised in Forest Hill by his mother Sandi after his parents separated, he first found fame as Jimmy Brooks on Canadian teen drama <em>Degrassi: The Next Generation</em> from 2001 to 2008. Music, however, was always the goal.</p>
            <p>His debut mixtape <em>Room for Improvement</em> dropped in 2006, followed by <em>Comeback Season</em> in 2007. But it was 2009's <em>So Far Gone</em> — a free download with “Best I Ever Had” — that turned him into the most talked-about new rapper in the world.</p>

            <h2>Rise</h2>
            <p>A bidding war ended with Drake signing to Lil Wayne's Young Money Entertainment. <em>Thank Me Later</em> (2010) debuted at #1. <em>Take Care</em> (2011) reframed what a rap album could sound like, splitting the difference between hip-hop and ambient R&amp;B. By <em>Nothing Was the Same</em> (2013) the formula was set: introspective, melodic, restless.</p>
            <p>The mixtape-as-album gambit of <em>If You're Reading This It's Too Late</em> (2015), the playlist <em>More Life</em> (2017), the double-LP <em>Scorpion</em> (2018) — every move expanded what mainstream rap could include. Dancehall, UK garage, Afrobeats, Jersey club: Drake folded them in.</p>

            <h2>The Iceman Era</h2>
            <p>After <em>Some Sexy Songs 4 U</em> with PARTYNEXTDOOR (2025) and the run of singles around it, Drake teased <em>Iceman</em> as the next chapter — a project rolled out as episodic drops. Cold sound, warm intention. The era is just beginning.</p>

